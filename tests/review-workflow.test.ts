import {expect, test} from 'bun:test';
import {createHash} from 'node:crypto';
import {mkdtemp, mkdir, readFile, writeFile, rm, symlink} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {sourceDigest, summaryText, type ReviewManifest} from '../src/review/artifacts';
import {readRevision, revisionSummary, matchedFrames} from '../src/review/revisions';
import {selectReviewFrames} from '../src/review/frames';
import {loadStudioProject} from '../src/spike/project';
import {createReviewApi} from '../src/studio/review-api';

test('historical revisions verify independently and compare only exact canonical identities', async () => {
  const base = await mkdtemp(join(tmpdir(), 'framecraft-revision-'));
  try {
    const projectRoot = join(base, 'project'); await mkdir(projectRoot);
    await writeFile(join(projectRoot, 'project.json'), JSON.stringify({schemaVersion:1, id:'study', video:{width:1,height:1,fps:30}, scenes:[{id:'intro',path:'scene.json'}],audio:[]}));
    await writeFile(join(projectRoot, 'scene.json'), JSON.stringify({id:'intro', shots:[{id:'only',entry:'shot.html',durationFrames:4,overlapFrames:0}],audio:[]}));
    await writeFile(join(projectRoot, 'shot.html'), '<!doctype html>');
    const digest = await sourceDigest(projectRoot);
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
    const frames = selectReviewFrames([{id:'only',startFrame:0,durationFrames:4}], []);
    const m: ReviewManifest = {schemaVersion:1,projectId:'study',sceneId:'intro',source:{gitCommit:'a'.repeat(40),trackedDirty:false,untrackedDirty:true,sha256:digest},selection:{policy:'boundaries-midpoints-v1',milestones:[]},environment:{bun:Bun.version,remotion:'4.0.537',chromium:'fixture',os:{platform:'linux',arch:'x64',release:'fixture'},video:{width:1,height:1,fps:30},fonts:null},validation:{command:'bun run validate',exitCode:0,warnings:[],errors:[]},captures:frames.map(f => ({...f,status:'captured',sha256:createHash('sha256').update(png).digest('hex')})),review:{status:'unreviewed',reviewer:null,findings:[],notes:''}};
    const revisionDir = join(base, 'revision'); await mkdir(join(revisionDir, 'screenshots'), {recursive:true});
    for (const f of frames) await writeFile(join(revisionDir,f.path),png);
    const save = async () => {await writeFile(join(revisionDir,'manifest.json'),JSON.stringify(m)); await writeFile(join(revisionDir,'summary.md'),summaryText(m));};
    await save(); const original = await readFile(join(revisionDir,'manifest.json'));
    const revision = await readRevision(revisionDir), a = revisionSummary(revision);
    await writeFile(join(projectRoot,'shot.html'),'Changed source');
    expect((await readRevision(revisionDir)).id).toBe(revision.id);
    expect(matchedFrames(a,{...a,id:'b'.repeat(64),sourceSha256:'c'.repeat(64)})).toHaveLength(3);
    for (const other of [{...a,sceneId:'other'},{...a,layout:'changed'},{...a,video:{...a.video,fps:24}},{...a,frames:a.frames.map(f=>({...f,globalFrame:f.globalFrame+1}))}]) expect(matchedFrames(a,other)).toHaveLength(0);
    const project = await loadStudioProject(projectRoot);
    const registry = {projects:new Map([['study',{root:projectRoot,project}]]),warnings:[]};
    await expect(createReviewApi(registry,projectRoot,[])).rejects.toThrow('inside');
    await expect(createReviewApi(registry,revisionDir,[revisionDir])).rejects.toThrow('inside');
    const api = await createReviewApi(registry,join(base,'workspace'),[revisionDir]);
    const call = async (path:string,init?:RequestInit) => {const request=new Request(`http://127.0.0.1:3000${path}`,init); return (await api(request,new URL(request.url)))!;};
    const query='/api/review?project=study&scene=intro';
    const body=await (await call(query)).json(); expect(body.etag).toBe('missing'); expect(body.sourceSha256).not.toBe(digest);
    const doc=body.feedback;
    const put = (etag:string, value:unknown=doc, origin='http://127.0.0.1:3000') => call(query,{method:'PUT',headers:{origin,'content-type':'application/json','if-match':etag},body:JSON.stringify(value)});
    expect((await put('missing',doc,'https://evil.example')).status).toBe(403);
    expect((await call(query,{method:'PUT',headers:{origin:'http://127.0.0.1:3000','content-type':'text/plain','if-match':'missing'},body:'{}'})).status).toBe(403);
    expect((await call(query,{method:'PUT',headers:{origin:'http://127.0.0.1:3000','content-type':'application/json','if-match':'missing'},body:'x'.repeat(1024*1024+1)})).status).toBe(413);
    expect((await call(query,{method:'PUT',headers:{origin:'http://127.0.0.1:3000','content-type':'application/json'},body:'{}'})).status).toBe(428);
    expect((await put('missing',{...doc,unknown:'/private/path'})).status).toBe(400);
    expect((await put('missing',{...doc,sceneId:'other'})).status).toBe(400);
    const issue={id:crypto.randomUUID(),projectId:'study',sceneId:'intro',shotId:'only',frame:3,localFrame:3,sourceSha256:body.sourceSha256,severity:'major',category:'timing',description:'Hold frame longer',status:'open',geometry:{type:'point',x:.5,y:.5}};
    expect((await put('missing',{...doc,issues:[{...issue,frame:4}]})).status).toBe(400);
    const saved=await put('missing',{...doc,issues:[issue]}); expect(saved.status).toBe(200);
    const savedBody=await saved.json(); expect((await put('missing')).status).toBe(409);
    expect((await (await call(query)).json()).feedback.issues).toHaveLength(1);
    expect((await call('/api/feedback-export?project=study&scene=intro&format=md')).status).toBe(200);
    expect((await call(`${query}&scene=intro`)).status).toBe(400);
    expect((await call('/api/review?project=..%2Fstudy&scene=intro')).status).toBe(400);
    expect((await call(`/api/revision-image?revision=${revision.id}&capture=0`)).status).toBe(200);
    expect((await call(`/api/revision-image?revision=${revision.id}&capture=../shot.html`)).status).toBe(404);
    expect((await put(savedBody.etag,{...doc,issues:[{...issue,sourceSha256:digest}]})).status).toBe(200);
    expect(await readFile(join(revisionDir,'manifest.json'))).toEqual(original);
    await writeFile(join(revisionDir,frames[0]!.path),'corrupt');
    expect((await call(`/api/revision-image?revision=${revision.id}&capture=0`)).status).toBe(422);
    await expect(readRevision(revisionDir)).rejects.toThrow('hash');
    await rm(join(revisionDir,frames[0]!.path)); await symlink(join(projectRoot,'shot.html'),join(revisionDir,frames[0]!.path));
    await expect(readRevision(revisionDir)).rejects.toThrow('escapes');
  } finally {await rm(base,{recursive:true,force:true});}
});
